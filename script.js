const body = document.body;
const langButtons = document.querySelectorAll("[data-lang]");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const translatablePlaceholders = document.querySelectorAll("[data-i18n-placeholder]");
const themeToggle = document.querySelector(".theme-toggle");
const navToggle = document.querySelector(".nav-toggle");
const navPanel = document.querySelector(".nav-panel");
const navLinks = document.querySelectorAll(".nav-links a");
const form = document.querySelector(".contact-form");
const sections = [...document.querySelectorAll("main section[id]")];
const pageTitle = document.querySelector("title");
const pageDescription = document.querySelector("meta[name='description']");
const ariaTranslatableNodes = document.querySelectorAll("[data-i18n-aria-label]");
const formStatus = document.querySelector(".form-status");

function safeStorageGet(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function safeStorageSet(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // Ignore storage errors so UI still works in private/restricted contexts.
  }
}

function applyLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) node.textContent = dictionary[key];
  });

  translatablePlaceholders.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) node.placeholder = dictionary[key];
  });

  ariaTranslatableNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (dictionary[key]) node.setAttribute("aria-label", dictionary[key]);
  });

  navToggle.setAttribute(
    "aria-label",
    navToggle.getAttribute("aria-expanded") === "true" ? dictionary["nav.closeMenu"] : dictionary["nav.openMenu"]
  );

  langButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === language);
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  if (pageTitle) {
    pageTitle.textContent = language === "az" ? "Murad | AI yönümlü məhsul qurucusu" : "Murad | AI odaklı ürün geliştirici";
  }

  if (pageDescription) {
    pageDescription.setAttribute(
      "content",
      language === "az"
        ? "Murad - AI yönümlü məhsul qurucusu, full stack developer və rəqəmsal həll yaradıcısı."
        : "Murad - AI odaklı ürün geliştirici, full stack developer ve dijital çözüm üreticisi."
    );
  }

  safeStorageSet("preferredLanguage", language);
}

function applyTheme(theme) {
  const isDark = theme === "dark";
  body.classList.toggle("dark-mode", isDark);
  themeToggle.setAttribute("aria-pressed", String(isDark));
  safeStorageSet("preferredTheme", theme);
}

function closeMobileMenu() {
  navPanel.classList.remove("is-open");
  navToggle.setAttribute("aria-expanded", "false");
  const currentLanguage = safeStorageGet("preferredLanguage") || "az";
  navToggle.setAttribute("aria-label", translations[currentLanguage]["nav.openMenu"]);
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

themeToggle.addEventListener("click", () => {
  applyTheme(body.classList.contains("dark-mode") ? "light" : "dark");
});

navToggle.addEventListener("click", () => {
  const isOpen = navPanel.classList.toggle("is-open");
  const currentLanguage = safeStorageGet("preferredLanguage") || "az";
  navToggle.setAttribute("aria-expanded", String(isOpen));
  navToggle.setAttribute("aria-label", isOpen ? translations[currentLanguage]["nav.closeMenu"] : translations[currentLanguage]["nav.openMenu"]);
});

navLinks.forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 920) closeMobileMenu();
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    const currentId = entry.target.id;
    navLinks.forEach((link) => {
      link.classList.toggle("is-active", link.getAttribute("href") === `#${currentId}`);
    });
  });
}, {
  rootMargin: "-40% 0px -45% 0px",
  threshold: 0.1
});

sections.forEach((section) => observer.observe(section));

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const submitButton = form.querySelector("button[type='submit']");
  const currentLanguage = safeStorageGet("preferredLanguage") || "az";
  submitButton.textContent = translations[currentLanguage]["contact.form.success"];
  submitButton.disabled = true;
  if (formStatus) formStatus.textContent = translations[currentLanguage]["contact.form.success"];

  setTimeout(() => {
    submitButton.textContent = translations[currentLanguage]["contact.form.submit"];
    submitButton.disabled = false;
    if (formStatus) formStatus.textContent = "";
    form.reset();
  }, 1600);
});

document.getElementById("year").textContent = new Date().getFullYear();

